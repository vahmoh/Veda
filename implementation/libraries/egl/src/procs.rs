//! `eglGetProcAddress`: every function of this library by its name, EGL's
//! and OpenGL ES's, core ones too (`EGL_KHR_get_all_proc_addresses`), and
//! the names OpenGL ES 2.0's extensions give 3.0's functions.
//!
//! A program that links the library refers to this function (libepoxy
//! weakly, to find all the others): the library's other functions come
//! into the program with it, through the table it reads.

