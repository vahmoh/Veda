/// Name and address pairs: a function under its own name, or under
/// another's (`alias => function`).
macro_rules! procs {
    ($($name:ident $(=> $target:ident)?),* $(,)?) => {
        vec![$(procs!(@one $name $(=> $target)?)),*]
    };
    (@one $name:ident) => { (stringify!($name), $name as *const () as usize) };
    (@one $name:ident => $target:ident) => { (stringify!($name), $target as *const () as usize) };
}

