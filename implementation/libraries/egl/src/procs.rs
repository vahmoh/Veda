/// `eglGetProcAddress`: the function named `procname`, or null.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn eglGetProcAddress(procname: *const c_char) -> *const c_void {
    if procname.is_null() {
        return std::ptr::null();
    }
    // SAFETY: the caller gives a NUL-terminated name.
    let Ok(name) = unsafe { CStr::from_ptr(procname) }.to_str() else { return std::ptr::null() };
    let t = table();
    t.binary_search_by_key(&name, |e| e.0).map_or(std::ptr::null(), |i| t[i].1 as *const c_void)
}

/// The names of every function `eglGetProcAddress` finds.
pub fn names() -> impl Iterator<Item = &'static str> {
    table().iter().map(|e| e.0)
}
