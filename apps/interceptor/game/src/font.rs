//! A stroke font for the signs: capital letters (and a few marks) as line
//! segments on a grid four units wide and six high, drawn as strokes of
//! any thickness: painted into the billboards' pictures, or built as the
//! tubes of a neon sign.

use alloc::vec::Vec;

use crate::prelude::*;

/// A glyph's strokes, `(x0, y0, x1, y1)` with y up.
type Strokes = &'static [(f32, f32, f32, f32)];

/// The width of a glyph and the space after it (units).
pub const ADVANCE: f32 = 5.4;
/// The height of a capital (units).
pub const CAP: f32 = 6.0;

